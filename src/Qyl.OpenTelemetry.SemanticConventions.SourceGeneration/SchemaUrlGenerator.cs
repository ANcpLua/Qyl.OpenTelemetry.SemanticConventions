namespace Qyl.OpenTelemetry.SemanticConventions.SourceGeneration;

/// <summary>
///   Emits a <c>Qyl.OpenTelemetry.SemanticConventions.Generated.SchemaUrl</c> constant
///   into the consumer's compilation. The schema version is read from a build-property
///   <c>QylSemConvSchemaVersion</c>, which the Nuke build component sets after it pulls
///   the upstream resolved-registry. Consumers that don't set the property fall back to
///   the version pinned in this assembly.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SchemaUrlGenerator : IIncrementalGenerator
{
    private const string DefaultSchemaVersion = "1.41.0";
    private const string SchemaUrlPrefix = "https://opentelemetry.io/schemas/";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<string> schemaVersion = context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) =>
                options.GlobalOptions.TryGetValue("build_property.QylSemConvSchemaVersion", out string? value)
                    && !string.IsNullOrWhiteSpace(value)
                    ? value
                    : DefaultSchemaVersion);

        context.RegisterSourceOutput(schemaVersion, static (sourceContext, version) =>
        {
            string source = $$"""
                // <auto-generated/>
                #nullable enable

                namespace Qyl.OpenTelemetry.SemanticConventions.Generated;

                /// <summary>
                ///   OpenTelemetry semantic-conventions schema URL pinned at build time
                ///   by Qyl.OpenTelemetry.SemanticConventions.SourceGeneration.
                /// </summary>
                public static class SchemaUrl
                {
                    /// <summary>Schema URL — emit on every Resource and OTLP export.</summary>
                    public const string Current = "{{SchemaUrlPrefix}}{{version}}";

                    /// <summary>Schema version that produced <see cref="Current"/>.</summary>
                    public const string Version = "{{version}}";
                }
                """;

            sourceContext.AddSource("SchemaUrl.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }
}
