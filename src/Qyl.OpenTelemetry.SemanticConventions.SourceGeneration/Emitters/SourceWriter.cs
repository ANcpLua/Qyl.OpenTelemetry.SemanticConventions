using System.Text;
using Qyl.OpenTelemetry.SemanticConventions.SourceGeneration.Models;

namespace Qyl.OpenTelemetry.SemanticConventions.SourceGeneration.Emitters;

/// <summary>
/// Shared text-emission primitives for every SemConv emitter (attributes, metrics,
/// meters, activities). Byte-identity snapshot tests enforce stable output,
/// so changes here are observable across all four surfaces at once.
/// </summary>
/// <remarks>
/// Two deliberate distinctions are preserved as separate members rather than
/// collapsed:
/// <list type="bullet">
///   <item><see cref="EscapeAttribute"/> collapses newlines to a space (attribute
///   arguments, and the meter emitter's unit/description literals); metric const
///   literals keep them, escaped via <c>StringExtensions.EscapeCSharpString</c>.</item>
///   <item><see cref="WriteObsolete"/> emits <c>[Obsolete]</c> only when a
///   deprecation model is present; <see cref="WriteStabilityObsolete"/> also emits
///   when the row's stability tier is itself <see cref="StabilityModel.Deprecated"/>.</item>
/// </list>
/// </remarks>
internal static class SourceWriter
{
    public static void WriteHeader(StringBuilder builder)
    {
        builder.AppendLine("// <auto-generated>This file has been auto generated from 'Qyl.OpenTelemetry.SemanticConventions.SourceGeneration'.</auto-generated>");
        builder.AppendLine();
        builder.AppendLine(GeneratedCodeHelpers.NullableEnable);
        builder.AppendLine();
        builder.AppendLine("#pragma warning disable CS1570 // XML comment has badly formed XML");
        builder.AppendLine();
    }

    public static void WriteNamespace(StringBuilder builder, string ns)
    {
        if (!string.IsNullOrEmpty(ns))
        {
            builder.Append("namespace ").Append(ns).AppendLine(";");
            builder.AppendLine();
        }
    }

    public static void WriteSummaryComment(StringBuilder builder, string text, int indent)
    {
        var pad = new string(' ', indent);
        builder.Append(pad).AppendLine("/// <summary>");
        foreach (var line in SplitLines(text))
            AppendDocLine(builder, pad, line);
        builder.Append(pad).AppendLine("/// </summary>");
    }

    public static void WriteRemarksComment(StringBuilder builder, string text, int indent)
    {
        var pad = new string(' ', indent);
        builder.Append(pad).AppendLine("/// <remarks>");
        foreach (var line in SplitLines(text))
            AppendDocLine(builder, pad, line);
        builder.Append(pad).AppendLine("/// </remarks>");
    }

    public static void WriteExamplesComment(StringBuilder builder, EquatableArray<string> examples, int indent)
    {
        if (examples.Length == 0)
            return;

        var pad = new string(' ', indent);
        builder.Append(pad).AppendLine("/// <remarks>");
        builder.Append(pad).AppendLine("/// Examples:");
        foreach (var example in examples)
            AppendExample(builder, pad, example);
        builder.Append(pad).AppendLine("/// </remarks>");
    }

    /// <summary>
    /// Writes one example as a <c>- </c> bullet, splitting on the example's own
    /// newlines so multi-line values (e.g. a JSON-array example) stay inside the
    /// XML doc comment instead of leaking raw lines into compilable source.
    /// </summary>
    public static void AppendExample(StringBuilder builder, string pad, string example)
    {
        var lines = example.Replace("\r", string.Empty).Split('\n');
        for (var i = 0; i < lines.Length; i++)
            AppendDocLine(builder, pad, i == 0 ? "- " + lines[i] : lines[i]);
    }

    public static void AppendDocLine(StringBuilder builder, string pad, string line)
    {
        builder.Append(pad).Append("///");
        if (!string.IsNullOrEmpty(line))
            builder.Append(' ').Append(line);
        builder.AppendLine();
    }

    /// <summary>Emits <c>[Obsolete]</c> iff <paramref name="deprecated"/> is present.</summary>
    public static void WriteObsolete(StringBuilder builder, DeprecatedModel? deprecated, int indent)
    {
        if (deprecated is null) return;
        AppendObsolete(builder, deprecated, indent);
    }

    /// <summary>
    /// Emits <c>[Obsolete]</c> when the row carries a deprecation model OR when its
    /// stability tier is itself <see cref="StabilityModel.Deprecated"/> (the meters
    /// and activities surfaces propagate stability=deprecated as an obsolete symbol).
    /// </summary>
    public static void WriteStabilityObsolete(
        StringBuilder builder,
        StabilityModel stability,
        DeprecatedModel? deprecated,
        int indent)
    {
        if (stability != StabilityModel.Deprecated && deprecated is null) return;
        AppendObsolete(builder, deprecated, indent);
    }

    private static void AppendObsolete(StringBuilder builder, DeprecatedModel? deprecated, int indent)
    {
        var pad = new string(' ', indent);
        builder.Append(pad).Append("[global::System.Obsolete(\"")
               .Append(EscapeAttribute(DeprecatedMessage(deprecated))).AppendLine("\")]");
    }

    public static string DeprecatedMessage(DeprecatedModel? deprecated) => deprecated switch
    {
        DeprecatedModel.Renamed r => $"Replaced by {r.RenamedTo}.",
        DeprecatedModel.Obsoleted => "Removed, no replacement.",
        DeprecatedModel.Uncategorized u => string.IsNullOrEmpty(u.Note) ? "Deprecated." : u.Note,
        _ => "Deprecated."
    };

    public static string RequirementLevelName(RequirementLevelKind kind) => kind switch
    {
        RequirementLevelKind.Required => "required",
        RequirementLevelKind.Recommended => "recommended",
        RequirementLevelKind.OptIn => "opt_in",
        RequirementLevelKind.ConditionallyRequired => "conditionally_required",
        _ => "unspecified"
    };

    public static string ToPascalCase(string value)
    {
        if (string.IsNullOrEmpty(value)) return string.Empty;

        var builder = new StringBuilder(value.Length);
        var upperNext = true;
        foreach (var ch in value)
        {
            if (ch is '.' or '_' or '-' or ' ')
            {
                upperNext = true;
                continue;
            }

            if (upperNext)
            {
                builder.Append(char.ToUpperInvariant(ch));
                upperNext = false;
            }
            else
            {
                builder.Append(ch);
            }
        }
        return builder.ToString();
    }

    public static IEnumerable<string> SplitLines(string text)
    {
        if (string.IsNullOrEmpty(text)) yield break;

        foreach (var line in text.Split('\n'))
            yield return line.TrimEnd('\r');
    }

    /// <summary>Escapes for a string literal where newlines collapse to a space (attribute args; meter unit/description).</summary>
    public static string EscapeAttribute(string text)
        => text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ").Replace("\r", string.Empty);
}
