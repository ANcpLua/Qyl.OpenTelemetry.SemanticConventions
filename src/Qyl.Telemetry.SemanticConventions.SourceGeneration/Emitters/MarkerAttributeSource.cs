namespace Qyl.Telemetry.SemanticConventions.SourceGeneration.Emitters;

/// <summary>
/// Builds the post-initialization source for a semantic-convention marker attribute.
/// Every class-level marker has the identical shape — an <c>internal sealed</c>
/// <c>[Conditional("QYL_SEMCONV_USAGES")]</c> attribute with a single
/// <c>(string prefix)</c> constructor; every assembly-level package-projection marker
/// takes <c>(string rootNamespace)</c> instead. Snapshot tests enforce the emitted shape.
/// </summary>
internal static class MarkerAttributeSource
{
    public static string For(string attributeClassName) => $$"""
        // <auto-generated/>
        #nullable enable
        namespace Qyl.Telemetry.SemanticConventions.SourceGeneration;

        [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
        [global::System.Diagnostics.Conditional("QYL_SEMCONV_USAGES")]
        internal sealed class {{attributeClassName}} : global::System.Attribute
        {
            public {{attributeClassName}}(string prefix)
            {
                Prefix = prefix;
            }

            public string Prefix { get; }
        }
        """;

    public static string ForAssembly(string attributeClassName) => $$"""
        // <auto-generated/>
        #nullable enable
        namespace Qyl.Telemetry.SemanticConventions.SourceGeneration;

        [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = false, Inherited = false)]
        [global::System.Diagnostics.Conditional("QYL_SEMCONV_USAGES")]
        internal sealed class {{attributeClassName}} : global::System.Attribute
        {
            public {{attributeClassName}}(string rootNamespace)
            {
                RootNamespace = rootNamespace;
            }

            public string RootNamespace { get; }
        }
        """;
}
